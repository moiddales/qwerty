"""Regenerate the catalog from the paper and problem cards' front matter.

Writes:
  himcm-modeling/catalog.json  machine-readable index (one entry per paper and problem)
  himcm-modeling/catalog.md    human-readable tables: papers by problem, model-family counts,
                               and which papers use each family

Run after adding or editing cards:  python3 tools/build_index.py
"""

import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_cards import FAMILIES, front_matter, parse_list  # noqa: E402

SKILL = Path(__file__).resolve().parent.parent / "himcm-modeling"
LIST_KEYS = ("model_families", "models", "tools", "deliverables", "data_sources", "tags", "papers", "problem_type")

FAMILY_LABELS = {
    "evaluation-mcdm": "Evaluation / multi-criteria decision (AHP, entropy weight, TOPSIS, scoring indices)",
    "statistics-regression": "Statistics and regression",
    "time-series-forecasting": "Time-series forecasting",
    "differential-equations": "Differential equations",
    "compartment-population": "Compartment and population models",
    "probability-stochastic": "Probability and stochastic processes",
    "queueing": "Queueing",
    "simulation-monte-carlo": "Monte Carlo simulation",
    "simulation-agent-cellular": "Agent-based / cellular automata / discrete-event simulation",
    "optimization-math-programming": "Mathematical programming (LP, IP, NLP, multi-objective)",
    "optimization-heuristic": "Heuristic optimization (GA, SA, PSO, greedy)",
    "graph-network": "Graphs, networks and routing",
    "machine-learning": "Machine learning",
    "physics-geometry": "Physics and geometry",
    "economics-cost-benefit": "Economics and cost-benefit",
    "spatial-geographic": "Spatial / geographic",
    "decision-game-theory": "Decision and game theory",
    "other": "Other",
}


def read_cards(folder):
    out = []
    for f in sorted((SKILL / folder).glob("*.md")):
        fm, _ = front_matter(f.read_text(encoding="utf-8"))
        if not fm:
            continue
        entry = {}
        for k, v in fm.items():
            entry[k] = parse_list(v) if k in LIST_KEYS else v.strip().strip('"')
        entry["card"] = f"{folder}/{f.name}"
        out.append(entry)
    return out


def main():
    papers = read_cards("papers")
    problems = read_cards("problems")
    for p in papers:
        for k in ("year", "pages"):
            if str(p.get(k, "")).isdigit():
                p[k] = int(p[k])
    (SKILL / "catalog.json").write_text(json.dumps({"problems": problems, "papers": papers}, indent=1,
                                                   ensure_ascii=False) + "\n", encoding="utf-8")

    by_problem = defaultdict(list)
    for p in papers:
        by_problem[f"{p['year']}{p['problem']}"].append(p)
    prob_meta = {pr["id"]: pr for pr in problems}
    fam_count = Counter(f for p in papers for f in (p.get("model_families") or []))
    fam_papers = defaultdict(list)
    for p in papers:
        for f in p.get("model_families") or []:
            fam_papers[f].append(p["id"])

    lines = [
        "# Catalog",
        "",
        "Generated by `tools/build_index.py` from the card front matter. Do not edit by hand.",
        "",
        f"{len(papers)} paper cards, {len(problems)} problem cards.",
        "",
        "## Papers by problem",
        "",
        "| Problem | Title | Paper | Paper title | Model families | Pages |",
        "|---|---|---|---|---|---|",
    ]
    for key in sorted(by_problem, reverse=True):
        title = prob_meta.get(key, {}).get("title") or by_problem[key][0].get("problem_title", "")
        prob_link = f"[{key}](problems/{key}.md)" if key in prob_meta else key
        for p in by_problem[key]:
            fams = ", ".join(p.get("model_families") or [])
            lines.append(f"| {prob_link} | {title} | [{p['id']}]({p['card']}) | {p.get('paper_title', '')} | {fams} | {p.get('pages', '')} |")
    lines += [
        "",
        "## Model families across the corpus",
        "",
        "Counts show how often a family appears among these papers. They describe this corpus only; they are not a ranking of methods.",
        "",
        "| Family | Papers | Paper ids |",
        "|---|---|---|",
    ]
    for f in sorted(FAMILIES, key=lambda x: (-fam_count[x], x)):
        if fam_count[f]:
            ids = ", ".join(f"[{i}](papers/{i}.md)" for i in fam_papers[f])
            lines.append(f"| {FAMILY_LABELS.get(f, f)} (`{f}`) | {fam_count[f]} | {ids} |")
    lines += ["", "## Problem types", "", "| Problem | Title | Types |", "|---|---|---|"]
    for pr in sorted(problems, key=lambda x: x["id"], reverse=True):
        lines.append(f"| [{pr['id']}](problems/{pr['id']}.md) | {pr.get('title', '')} | {', '.join(pr.get('problem_type') or [])} |")
    # Every paper in the corpus, including those with no card yet (full text is always available).
    manifest = SKILL.parent / "tools" / "booklet_manifest.json"
    extra = []
    if manifest.exists():
        man = json.loads(manifest.read_text(encoding="utf-8"))
        titles = dict(man.get("problems", {}))
        carded = {p["id"] for p in papers}
        for f in sorted((SKILL / "corpus" / "papers").glob("*.md")):
            fm, _ = front_matter(f.read_text(encoding="utf-8"))
            if fm and fm.get("id") and fm["id"] not in {m["id"] for m in man["papers"]}:
                extra.append(fm)  # papers added later with tools/ingest.py
        rows = [(m["id"], m["year"], m["problem"], m.get("award", "")) for m in man["papers"]]
        rows += [(e["id"], e.get("year", ""), e.get("problem", ""), e.get("award", "").strip('"')) for e in extra]
        lines += [
            "",
            "## All papers in the corpus",
            "",
            f"{len(rows)} papers. Every paper has a page-marked full text in `corpus/papers/` and the original PDF "
            "in `sources/papers/` (repository root). Papers without a card can still be read and cited directly.",
            "",
            "| Problem | Title | Paper | Award | Card | Full text |",
            "|---|---|---|---|---|---|",
        ]
        for pid, year, prob, award in sorted(rows, key=lambda r: (-int(r[1] or 0), r[2], r[0])):
            key = f"{year}{prob}"
            card = f"[card](papers/{pid}.md)" if pid in carded else "-"
            lines.append(f"| {key} | {titles.get(key, '')} | {pid} | {award} | {card} | "
                         f"[text](corpus/papers/{pid}.md) |")
        lines += ["", "## Official problem statements", "", "| Problem | Title | Statement | Problem card |", "|---|---|---|---|"]
        for f in sorted((SKILL / "corpus" / "problems").glob("*.md"), reverse=True):
            fm, _ = front_matter(f.read_text(encoding="utf-8"))
            pid = f.stem
            card = f"[card](problems/{pid}.md)" if pid in prob_meta else "-"
            lines.append(f"| {pid} | {(fm or {}).get('title', '').strip(chr(34))} | [statement](corpus/problems/{f.name}) | {card} |")
    (SKILL / "catalog.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"catalog: {len(papers)} paper cards, {len(problems)} problem cards")


if __name__ == "__main__":
    main()
